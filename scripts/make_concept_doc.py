"""
make_concept_doc.py — สร้างเอกสาร Word "แนวคิด · วิธีทำงาน · ผลลัพธ์"
=====================================================================
เนื้อหาซื่อสัตย์: แยก "ผลที่มีจริงแล้ว" ออกจาก "ผลที่รอข้อมูลนักเรียน"
ไม่มีตัวเลขผลการทดลองจากนักเรียนที่ยังไม่มี
"""
import os
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn

THAI_FONT = "Leelawadee UI"
INK = RGBColor(0x1c, 0x1c, 0x1e)
NAVY = RGBColor(0x0f, 0x17, 0x2a)
SLATE = RGBColor(0x33, 0x41, 0x55)
RED = RGBColor(0xb9, 0x1c, 0x1c)

doc = Document()

# ---- ตั้งฟอนต์ไทยเป็นค่าเริ่มต้น ----
normal = doc.styles["Normal"]
normal.font.name = THAI_FONT
normal.font.size = Pt(11)
normal.font.color.rgb = INK
normal.element.rPr.rFonts.set(qn("w:cs"), THAI_FONT)   # complex-script (ไทย)
normal.element.rPr.rFonts.set(qn("w:eastAsia"), THAI_FONT)
for s in doc.sections:
    s.top_margin = s.bottom_margin = Cm(1.8)
    s.left_margin = s.right_margin = Cm(2.0)


def _set_cs(run):
    run.font.name = THAI_FONT
    rpr = run._element.get_or_add_rPr()
    rf = rpr.get_or_add_rFonts()
    rf.set(qn("w:cs"), THAI_FONT)
    rf.set(qn("w:eastAsia"), THAI_FONT)


def para(text="", bold=False, size=11, color=INK, align=None, space_after=6, italic=False):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    # รองรับ **ตัวหนา** ในข้อความ
    parts = text.split("**")
    for i, seg in enumerate(parts):
        if not seg:
            continue
        r = p.add_run(seg)
        r.bold = bold or (i % 2 == 1)
        r.italic = italic
        r.font.size = Pt(size)
        r.font.color.rgb = color
        _set_cs(r)
    return p


def h1(text):
    para(text, bold=True, size=22, color=NAVY, space_after=4)


def sub(text):
    para(text, size=12, color=SLATE, italic=True, space_after=10)


def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(15)
    r.font.color.rgb = NAVY
    _set_cs(r)
    # เส้นใต้หัวข้อ
    pPr = p._p.get_or_add_pPr()
    pbdr = pPr.makeelement(qn("w:pBdr"), {})
    bottom = pbdr.makeelement(qn("w:bottom"), {
        qn("w:val"): "single", qn("w:sz"): "6", qn("w:space"): "3", qn("w:color"): "cbd5e1"})
    pbdr.append(bottom)
    pPr.append(pbdr)


def h3(text):
    para(text, bold=True, size=12.5, color=SLATE, space_after=3)


def bullet(text, size=11):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    parts = text.split("**")
    for i, seg in enumerate(parts):
        if not seg:
            continue
        r = p.add_run(seg)
        r.bold = (i % 2 == 1)
        r.font.size = Pt(size)
        r.font.color.rgb = INK
        _set_cs(r)


def table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(htext)
        r.bold = True
        r.font.size = Pt(10)
        r.font.color.rgb = NAVY
        _set_cs(r)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            parts = str(val).split("**")
            pph = cells[i].paragraphs[0]
            for j, seg in enumerate(parts):
                if not seg:
                    continue
                r = pph.add_run(seg)
                r.bold = (j % 2 == 1)
                r.font.size = Pt(9.5)
                r.font.color.rgb = INK
                _set_cs(r)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def quote(text, color=NAVY):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.6)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(8)
    parts = text.split("**")
    for i, seg in enumerate(parts):
        if not seg:
            continue
        r = p.add_run(seg)
        r.bold = (i % 2 == 1)
        r.italic = True
        r.font.size = Pt(11)
        r.font.color.rgb = color
        _set_cs(r)
    pPr = p._p.get_or_add_pPr()
    pbdr = pPr.makeelement(qn("w:pBdr"), {})
    left = pbdr.makeelement(qn("w:left"), {
        qn("w:val"): "single", qn("w:sz"): "18", qn("w:space"): "8", qn("w:color"): "f59e0b"})
    pbdr.append(left)
    pPr.append(pbdr)


