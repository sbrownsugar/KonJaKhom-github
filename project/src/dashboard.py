"""
dashboard.py — แดชบอร์ดครู (ระดับกลุ่ม ไม่ระบุตัวตน)
=============================================================================
หลักคิดเดียวที่ทำให้หน้านี้มีค่า:

   ปัจจัยเสี่ยงที่ "ปรับได้" มี 6 ตัว — และ 4 ใน 6 ตัว
   **อยู่ในมือโรงเรียน ไม่ใช่ในมือเด็ก**

   เวลานั่งต่อเนื่อง  <- ตารางเรียน + คาบติดกัน   = โรงเรียนคุม
   การขยับระหว่างวัน  <- มีเวลาให้ลุกไหม           = โรงเรียนคุม
   ชั่วโมงนอน        <- การบ้าน + เวลาเลิกเรียน   = โรงเรียนคุม (บางส่วน)
   ความเครียด        <- ปริมาณสอบ + ตารางสอบ      = โรงเรียนคุม (บางส่วน)
   เวลาหน้าจอ        <- เด็กคุม
   การออกกำลังกาย    <- เด็ก + คาบพละ

=> บอกเด็กคนเดียวให้ "นั่งตัวตรง" แก้อะไรไม่ได้ ถ้าตารางเรียนบังคับให้นั่ง 4 คาบติด
=> แดชบอร์ดนี้จึงไม่ได้มีไว้ "จับเด็ก" แต่มีไว้ให้ "โรงเรียนเห็นสิ่งที่โรงเรียนแก้ได้"

*** กฎความเป็นส่วนตัวที่บังคับในโค้ด (ไม่ใช่แค่พูด) ***
  * ห้องที่มีผู้ตอบ < 10 คน -> ปิดทั้งแถว ไม่แสดงตัวเลขใด ๆ
  * ไม่มีชื่อ ไม่มีคะแนนรายบุคคล ไม่มีภาพ
  * ไม่แสดง BMI ให้ครู/ผอ. เห็น (กันการตีตราเรื่องน้ำหนัก)
"""
from __future__ import annotations

import numpy as np
import pandas as pd

MIN_CELL = 10          # ห้องที่มีคนน้อยกว่านี้ = ปิดข้อมูลทั้งแถว
MIN_TOTAL = 20         # ผู้ตอบทั้งชุดน้อยกว่านี้ = ไม่แสดงอะไรเลย แม้แต่ภาพรวม

# =============================================================================
# *** 2 รูรั่วที่กฎ "n < 10" ตัวเดียวอุดไม่ได้ ***
#
# รูที่ 1 — กฎเดิมคุมแค่ "รายห้อง" ไม่คุม "ภาพรวม"
#   ครูอัปโหลดไฟล์ที่มีนักเรียน 5 คน -> ทุกห้องถูกปิด ✅
#   แต่การ์ด "ภาพรวมทั้งโรงเรียน" ยังโชว์ "เครียดสูง 80%" = 4 ใน 5 คน
#   ในห้องที่มีเด็กตอบ 5 คน ครูเดาได้ไม่ยากว่าใครคือ 4 คนนั้น
#   -> ต้องมี MIN_TOTAL คุมอีกชั้น
#
# รูที่ 2 — differencing attack (ทางลอดที่กฎ n<10 มองไม่เห็น)
#   สมมติมี 3 ห้อง: ม.5/1 (30 คน) · ม.5/2 (25 คน) · ม.5/3 (8 คน)
#   ตารางโชว์ 5/1 กับ 5/2 และ "ปิด" 5/3 เพราะคนน้อย
#   แต่ครูเห็น "ภาพรวม 63 คน" อยู่ข้างบน  ->  63 − 30 − 25 = 8 คน
#   และเอาค่าเฉลี่ยรวมลบค่าเฉลี่ยที่โชว์ -> **ได้ตัวเลขของห้องที่ปิดไว้ครบทุกช่อง**
#   = การปิดข้อมูลไม่ได้ปิดอะไรเลย เป็นแค่การซ่อนที่หลอกตัวเอง
#
#   วิธีแก้มาตรฐานของหน่วยงานสถิติ = complementary suppression
#   "ถ้าปิดไป 1 ห้อง ต้องปิดอีกห้องที่เล็กที่สุดที่เหลือด้วย"
#   เพราะการหักลบจะให้ผลรวมของ 2 ห้อง ไม่ใช่ห้องเดียว -> ระบุตัวไม่ได้
# =============================================================================

# ตัวขับที่ปรับได้ + ใครคุมมัน (ใช้ตัดสินว่าโรงเรียน "ทำอะไรได้จริง")
DRIVERS = [
    ("นอน < 7 ชม.",            "sleep_lt7",  "โรงเรียน (การบ้าน/เวลาเลิกเรียน)"),
    ("เครียดสูง (≥7/10)",      "stress_hi",  "โรงเรียน (ปริมาณสอบ/ตารางสอบ)"),
    ("นั่ง ≥ 6 ชม./วัน",       "sit_hi",     "โรงเรียน (ตารางเรียน/คาบติดกัน)"),
    ("ออกกำลังกาย < 2 วัน/สัปดาห์", "ex_low", "โรงเรียน + เด็ก (คาบพละ)"),
    ("ก้มมือถือ ≥ 4 ชม./วัน",  "phone_hi",   "เด็ก"),
]


def prepare(d: pd.DataFrame, room_col: str | None = None) -> pd.DataFrame:
    """แปลงข้อมูลดิบ -> ธงระดับบุคคล (ยังไม่รวมกลุ่ม)"""
    out = pd.DataFrame(index=d.index)
    out["sleep_lt7"] = (d["sleep_hr"] < 7).astype(float)
    out["stress_hi"] = (d["stress"] >= 7).astype(float)
    out["sit_hi"] = (d["sit_hr"] >= 6).astype(float)
    out["ex_low"] = (d["exercise_d"] < 2).astype(float)
    out["phone_hi"] = (d["phone_hr"] >= 4).astype(float)
    out["red_flag"] = d["red_flag"].astype(float) if "red_flag" in d else 0.0
    out["nrs"] = d["nrs"] if "nrs" in d else np.nan

    # ห้องเรียน: จากรหัส "5101" -> ม.5/1
    if room_col is not None and room_col in d:
        code = d[room_col].astype(str).str.extract(r"(\d{2})")[0]
        out["room"] = code.map(lambda c: "ม.%s/%s" % (c[0], c[1]) if isinstance(c, str) and len(c) == 2 else None)
    else:
        out["room"] = "ทั้งโรงเรียน"
    return out


def by_room(f: pd.DataFrame) -> pd.DataFrame:
    """สรุปรายห้อง + ปิดเซลล์ที่คนน้อยเกินไป + อุดทางลอด differencing"""
    sizes = f.groupby("room", dropna=True).size().sort_values()      # เล็ก -> ใหญ่

    # 1) ห้องที่คนน้อยกว่าเกณฑ์ = ปิดแน่นอน (primary suppression)
    suppressed = set(sizes[sizes < MIN_CELL].index)

    # 2) complementary suppression — ถ้าปิดไปแค่ห้องเดียว
    #    ครูหักลบ (ภาพรวม − ห้องที่โชว์) ก็ได้ห้องนั้นกลับมาทันที
    #    -> ต้องปิดห้องที่ "เล็กที่สุดที่เหลือ" เพิ่มอีก 1 ห้อง (เสียข้อมูลน้อยที่สุด)
    #       หักลบแล้วจะได้ "ผลรวมของ 2 ห้อง" ซึ่งแยกกลับเป็นห้องเดียวไม่ได้
    #
    # ทำไมพอแค่ 2 ห้อง? สมการมี 1 บรรทัด (ผลรวม) แต่ไม่รู้ค่า 2 ตัว -> แก้ไม่ได้
    # และห้ามปิดเพิ่มเกินจำเป็น เพราะการปิดทุกอย่างก็คือการทำให้แดชบอร์ดไร้ประโยชน์
    # (การรู้ "จำนวนคน" ของห้องที่ปิด ไม่ช่วยให้แยกได้ -> โชว์จำนวนคนได้ ไม่รั่ว)
    if len(suppressed) == 1:
        for room in sizes.index:                 # sizes เรียงจากเล็กไปใหญ่แล้ว
            if room not in suppressed:
                suppressed.add(room)
                break

    rows = []
    for room, sub in f.groupby("room", dropna=True):
        n = len(sub)
        if room in suppressed:
            rows.append({"ห้อง": room, "จำนวนผู้ตอบ": n,
                         **{lbl: None for lbl, _, _ in DRIVERS},
                         "ควรพบผู้เชี่ยวชาญ": None,
                         "_ปิดข้อมูล": True})
            continue
        rows.append({
            "ห้อง": room, "จำนวนผู้ตอบ": n,
            **{lbl: 100.0 * sub[key].mean() for lbl, key, _ in DRIVERS},
            "ควรพบผู้เชี่ยวชาญ": 100.0 * sub["red_flag"].mean(),
            "_ปิดข้อมูล": False,
        })
    return pd.DataFrame(rows).sort_values("ห้อง").reset_index(drop=True)


def school_summary(f: pd.DataFrame) -> dict:
    """สรุปภาพรวม — คืน too_small=True ถ้าผู้ตอบน้อยเกินกว่าจะแสดงอะไรได้อย่างปลอดภัย"""
    n = len(f)
    if n < MIN_TOTAL:
        # ไม่คำนวณอะไรเลย ไม่ใช่แค่ไม่แสดง — จะได้ไม่มีตัวเลขหลุดออกไปทาง log/export
        return {"n": n, "too_small": True, "drivers": [],
                "red_flag_pct": float("nan"), "nrs_mean": float("nan")}
    return {
        "n": n,
        "too_small": False,
        "drivers": [(lbl, 100.0 * f[key].mean(), who) for lbl, key, who in DRIVERS],
        "red_flag_pct": 100.0 * f["red_flag"].mean(),
        "nrs_mean": float(f["nrs"].mean()) if "nrs" in f else float("nan"),
    }


def top_actions(summary: dict, k: int = 3) -> list:
    """เรียงตัวขับจาก 'พบมากที่สุด' และคัดเฉพาะตัวที่โรงเรียนทำอะไรได้"""
    school = [d for d in summary["drivers"] if d[2].startswith("โรงเรียน")]
    school.sort(key=lambda t: -t[1])
    return school[:k]


