# *** ทำไมห้ามโชว์ probability เป็น % ให้ผู้ใช้เห็น ***
#
# การเอา ln(OR) จากงานวิจัยคนละชิ้นมาบวกกัน มันตั้งอยู่บนสมมติฐานว่า
# "ปัจจัยแต่ละตัวเป็นอิสระต่อกัน" ซึ่ง *ไม่จริง* (คนเครียดมักนอนน้อย, คนนอนน้อยมักไม่ออกกำลังกาย)
# ผลคือคะแนนพองเกินจริงเสมอ -> เคสตัวอย่างได้ 94% ซึ่ง "ไม่มีทางพิสูจน์ได้"
#
# สิ่งที่เราพิสูจน์ได้จริง คือ "การจัดอันดับ" (ranking):
#   คนที่นอนน้อย+เครียด+ไม่ออกกำลังกาย เสี่ยงกว่าคนที่ทำครบ  <- อันนี้หลักฐานรองรับ
# สิ่งที่เราพิสูจน์ไม่ได้ คือ "ตัวเลขสัมบูรณ์"
#   คนนี้จะปวดที่ 94% พอดี                                   <- อันนี้โม้
#
# => UI จึงโชว์  "เสี่ยงกว่าเพื่อนร่วมรุ่นโดยเฉลี่ย X เท่า"  และ  "อยู่ในกลุ่มไหน (เขียว/เหลือง/แดง)"
#    ไม่โชว์ % เด็ดขาด  และเมื่อได้ข้อมูล 100 คนแล้ว ให้ใช้ 'เปอร์เซ็นไทล์ในกลุ่มจริง' แทน
# -----------------------------------------------------------------------------


def _bmi(weight_kg: float, height_cm: float) -> float:
    if not weight_kg or not height_cm:
        return 0.0
    m = height_cm / 100.0
    return weight_kg / (m * m) if m > 0 else 0.0


# =============================================================================
# เกณฑ์ "น้ำหนักเกิน" สำหรับวัยรุ่น — *ไม่ใช่* BMI >= 25 แบบผู้ใหญ่
#
# *** บั๊กเดิม: ใช้ BMI >= 25 กับเด็ก ม.ปลาย ซึ่งผิดหลักกุมารเวชศาสตร์ ***
# ร่างกายวัยรุ่นยังเติบโต -> เกณฑ์ต้องขึ้นกับ "อายุ + เพศ"
# WHO Growth Reference (5-19 ปี): overweight = BMI-for-age z-score > +1SD
# (ค่า +1SD ค่อย ๆ ไต่ขึ้นตามอายุ จนบรรจบ BMI 25 พอดีตอนอายุ 19 ปี)
#
# ตารางด้านล่าง = ค่า BMI ที่ +1SD ตามอายุและเพศ (WHO 2007 BMI-for-age)
# https://www.who.int/tools/growth-reference-data-for-5to19-years
# =============================================================================
BMI_OVERWEIGHT_CUTOFF = {
    # อายุ: (ชาย, หญิง)
    13: (21.9, 22.6),
    14: (22.6, 23.3),
    15: (23.3, 23.9),
    16: (23.9, 24.4),
    17: (24.5, 24.7),
    18: (25.0, 25.0),
    19: (25.0, 25.0),
}


def _is_overweight(bmi: float, age: float | None, sex: str | None) -> float:
    """คืน 1.0 ถ้าน้ำหนักเกินตามเกณฑ์วัยรุ่น (BMI-for-age > +1SD)"""
    if bmi <= 0:
        return 0.0
    a = int(round(age)) if age else 17          # ไม่รู้อายุ -> ใช้ ม.5 (17 ปี) เป็นค่ากลาง
    a = max(13, min(19, a))
    male_cut, female_cut = BMI_OVERWEIGHT_CUTOFF[a]
    cut = female_cut if sex == "หญิง" else male_cut
    return 1.0 if bmi >= cut else 0.0


def build_predictors(ans: dict) -> dict:
    """แปลงคำตอบดิบจากแบบสอบถาม -> ตัวแปรตามนิยามในงานวิจัย

    *** ค่า default ตอนข้อมูลหาย ***
    เดิมเราใช้ default ที่ "ปลอดภัยเกินจริง" (ไม่ตอบ = ถือว่าไม่เสี่ยง)
    -> คนที่ข้ามคำถามจะถูกประเมินว่าดีกว่าความจริง
    ตอนนี้: ไม่ตอบ = ใช้ค่าเฉลี่ยประเทศ (ไม่ได้เปรียบไม่เสียเปรียบ) และคืน missing ให้ผู้เรียกรู้
    """
    ref = REFERENCE_NATIONAL
    missing = []

    def num(key, default_ref):
        v = ans.get(key)
        if v is None or (isinstance(v, float) and v != v):
            missing.append(key)
            return None
        return float(v)

    bmi = _bmi(ans.get("weight_kg", 0) or 0, ans.get("height_cm", 0) or 0)
    w = ans.get("weight_kg") or 0
    bag_pct = (100.0 * (ans.get("bag_kg") or 0) / w) if w else 0.0

    sleep = num("sleep_hr", None)
    stress = num("stress_0_10", None)
