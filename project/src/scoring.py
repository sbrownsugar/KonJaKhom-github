    #        แล้วได้คะแนนความเสี่ยง *ต่ำ* — ระบบพลาดคนที่ควรจับให้ได้มากที่สุด
    # และค่าอ้างอิง REFERENCE_NATIONAL["hx_pain_12mo"] = 0.42 (Keeratisiroj) ก็เป็น
    # ความชุก "ภายใน 12 เดือน" อยู่แล้ว -> ตัวตั้งกับตัวเทียบเคยไม่ใช่เรื่องเดียวกันด้วยซ้ำ
    #
    # แก้: ใช้คีย์ "hx_pain_12mo" (ภายใน 12 เดือน) ให้ตรงกับทั้ง β และ REFERENCE
    #      คีย์เก่ารับไว้เพื่อความเข้ากันได้ แต่ไม่ควรมีใครส่งมาแล้ว
