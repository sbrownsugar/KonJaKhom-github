    #     "เคยมีอาการปวดคอ/ไหล่/หลัง ***ภายใน 12 เดือนที่ผ่านมา***"
    # แต่แอปเราดันไปถามว่า
    #     "***ก่อนหน้า*** 1 ปีที่แล้ว (นานกว่า 1 ปีมาแล้ว)"   <-- คนละช่วงเวลา แทบตรงข้าม
    #
